// SHA-256 in plain JavaScript. The plugin runs in a null-origin sandbox
// frame, which is not a secure context, so crypto.subtle may be missing
// there. Safe Browsing needs one hash per URL expression (at most 30 per
// click), each a few dozen bytes, so speed doesn't matter.

